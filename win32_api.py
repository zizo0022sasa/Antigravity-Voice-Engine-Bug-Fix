def get_process_exe_name(hwnd: int) -> str:
    """
    Resolves the executable filename (e.g. 'Antigravity IDE.exe' or 'explorer.exe')
    for a window handle using PROCESS_QUERY_LIMITED_INFORMATION (works across UIPI).
    Returns '' on failure (callers treat '' as fail-open per R5).
    """
    if not hwnd:
        return ""
    pid = wintypes.DWORD(0)
    user32.GetWindowThreadProcessId(hwnd, ctypes.byref(pid))
    if not pid.value:
        return ""
    hproc = kernel32.OpenProcess(PROCESS_QUERY_LIMITED_INFORMATION, False, pid.value)
    if not hproc:
        return ""
    try:
        size = wintypes.DWORD(1024)
        buf = ctypes.create_unicode_buffer(1024)
        if kernel32.QueryFullProcessImageNameW(hproc, 0, buf, ctypes.byref(size)):
            return os.path.basename(buf.value)
        return ""
    finally:
        kernel32.CloseHandle(hproc)


def is_input_desktop_accessible() -> bool:
    """
    Returns False when Windows is on the Secure Desktop (Win+L Lock Screen or UAC prompt),
    where WH_KEYBOARD_LL hooks do not receive KeyUp events (V21-01).
    """
    try:
        hdesk = user32.OpenInputDesktop(0, False, GENERIC_READ)
        if not hdesk:
            return False
        user32.CloseDesktop(hdesk)
        return True
    except Exception:
        return True

